// Run against dev or preview: node tools/lab-browser.mjs http://127.0.0.1:5173
import assert from 'node:assert/strict';
import { chromium } from 'playwright';
const url = process.argv[2] ?? 'http://127.0.0.1:5173';
const browser = await chromium.launch({ args: ['--no-sandbox', '--enable-webgl', '--enable-unsafe-swiftshader', '--use-gl=angle', '--use-angle=swiftshader'] });
const errors = [];
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
  page.on('pageerror', (e) => errors.push(e.message));
  page.on('console', (m) => { if (m.type() === 'error' && /WebGL|shader/i.test(m.text())) errors.push(m.text()); });
  await page.goto(`${url}/?swim=0&breathe=0&shot=4`, { waitUntil: 'domcontentloaded' });
  await page.waitForFunction(() => window.__frames >= 4, undefined, { timeout: 75000 });
  assert.equal(await page.locator('h1').textContent(), 'Slate Reef Shark');
  assert.equal(await page.locator('canvas').count(), 1);
  assert.ok(await page.getByRole('img', { name: /tiger shark, reference/i }).evaluate((img) => img.complete && img.naturalWidth > 100));
  const jaw = page.getByRole('slider', { name: 'Jaw opening' });
  await jaw.fill('0.8');
  assert.notEqual(await page.locator('.jaw-slider output').textContent(), '0°');
  await page.getByRole('button', { name: 'Mouth', exact: true }).click();
  assert.equal(await page.getByRole('button', { name: 'Mouth', exact: true }).getAttribute('aria-pressed'), 'true');
  await page.getByRole('button', { name: 'Zoom in', exact: true }).click();
  const fins = page.getByRole('switch', { name: 'Fin motion' });
  await fins.click();
  assert.equal(await fins.getAttribute('aria-checked'), 'false');
  await page.getByRole('button', { name: 'Trigger strike', exact: true }).click();
  assert.equal(await jaw.inputValue(), '0');
  await page.getByRole('button', { name: 'Reef manta', exact: false }).click();
  await page.getByRole('heading', { name: 'Sandy-spotted Coral Manta', level: 1 }).waitFor({ timeout: 50000 });
  await page.getByRole('button', { name: 'Generate specimen', exact: false }).click();
  await page.waitForURL(/\?hab=reef&seed=/, { timeout: 50000 });
  await page.getByRole('button', { name: 'Atlas 106' }).click();
  await page.getByRole('textbox', { name: 'Search the atlas' }).fill('longhorn');
  await page.getByRole('button', { name: /Longhorn Cowfish/ }).click();
  await page.getByRole('heading', { name: 'Longhorn Cowfish', level: 1 }).waitFor({ timeout: 50000 });
  await page.getByRole('button', { name: 'Keyboard shortcuts', exact: true }).click();
  assert.ok(await page.getByRole('dialog').isVisible());
  await page.keyboard.press('Escape');
  await page.getByRole('dialog').waitFor({ state: 'hidden' });
  await page.close();
  const phone = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true });
  phone.on('pageerror', (e) => errors.push(e.message));
  await phone.goto(`${url}/?shot=3`, { waitUntil: 'domcontentloaded' });
  await phone.getByRole('button', { name: 'Toggle generator' }).click();
  assert.ok(await phone.getByRole('complementary', { name: 'Species generator' }).isVisible());
  await phone.getByRole('button', { name: 'Close generator' }).click();
  await phone.getByRole('button', { name: 'Toggle field guide' }).click();
  assert.ok(await phone.getByRole('complementary', { name: 'Field guide' }).isVisible());
  assert.deepEqual(errors, []);
  console.log('WebGL, jaw controls, camera, fin toggle, presets, generation, atlas search, keyboard help and mobile panels passed.');
} finally { await browser.close(); }
